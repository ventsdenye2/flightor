/** 射线法：点是否在多边形内 */
function inRing(lng: number, lat: number, ring: Ring): boolean {
  let inside = false
  for (let i = 0, j = ring.length - 1; i < ring.length; j = i++) {
    const [xi, yi] = ring[i]
    const [xj, yj] = ring[j]
    if (yi > lat !== yj > lat && lng < ((xj - xi) * (lat - yi)) / (yj - yi) + xi) {
      inside = !inside
    }
  }
  return inside
}

let cache: Array<[number, number]> | null = null

/** 大陆点阵（[lng, lat]，步长 3°），模块级缓存 */
export function getLandDots(): Array<[number, number]> {
  if (cache) return cache
  const dots: Array<[number, number]> = []
  for (let lat = -56; lat <= 80; lat += 3) {
    for (let lng = -180; lng <= 180; lng += 3) {
      if (POLYGONS.some(ring => inRing(lng, lat, ring))) {
        dots.push([lng, lat])
      }
    }
  }
  cache = dots
  return dots
}
